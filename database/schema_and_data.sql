/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE tema CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE categoria CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE usuario CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE rol CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE rol (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE usuario (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  email VARCHAR2(180) NOT NULL UNIQUE,
  password VARCHAR2(255) NOT NULL,
  rol_id NUMBER NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol(id)
);

CREATE TABLE categoria (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(80) NOT NULL UNIQUE,
  descripcion VARCHAR2(300)
);

CREATE TABLE tema (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  titulo VARCHAR2(200) NOT NULL,
  contenido CLOB NOT NULL,
  categoria_id NUMBER NOT NULL,
  usuario_id NUMBER NOT NULL,
  oculto NUMBER(1) DEFAULT 0 NOT NULL,
  fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_tema_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id),
  CONSTRAINT fk_tema_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE comentario (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  contenido CLOB NOT NULL,
  tema_id NUMBER NOT NULL,
  usuario_id NUMBER NOT NULL,
  oculto NUMBER(1) DEFAULT 0 NOT NULL,
  fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_comentario_tema FOREIGN KEY (tema_id) REFERENCES tema(id) ON DELETE CASCADE,
  CONSTRAINT fk_comentario_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

